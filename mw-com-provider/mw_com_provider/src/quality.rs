use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, Deserialize, Eq, Ord, PartialEq, PartialOrd, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum SignalQuality {
    Invalid,
    Stale,
    Degraded,
    Valid,
}

impl Default for SignalQuality {
    fn default() -> Self {
        Self::Valid
    }
}
